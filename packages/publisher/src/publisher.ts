/**
 * Main Publisher class - orchestrates the publish workflow
 */

import { readFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { createHash } from 'node:crypto';
import type { Config, PublishResult, PageNode, AttachmentRef } from './types.js';
import { ConfluenceClient } from './confluence/client.js';
import { TreeBuilder } from './tree/builder.js';
import { MarkdownConverter } from './markdown/converter.js';

export interface PublisherConfig {
  config: Config;
  email: string;
  apiToken: string;
}

export class Publisher {
  private config: Config;
  private client: ConfluenceClient;
  private treeBuilder: TreeBuilder;
  private converter: MarkdownConverter;

  constructor(publisherConfig: PublisherConfig) {
    this.config = publisherConfig.config;
    this.client = new ConfluenceClient({
      baseUrl: this.config.confluence.baseUrl,
      email: publisherConfig.email,
      apiToken: publisherConfig.apiToken,
    });
    this.treeBuilder = new TreeBuilder(this.config);
    this.converter = new MarkdownConverter();
  }

  async publish(): Promise<PublishResult> {
    const result: PublishResult = {
      created: [],
      updated: [],
      unchanged: [],
      warnings: [],
      errors: [],
    };

    try {
      // Step 1: Build the page tree from local files
      console.log('Building page tree from local files...');
      const tree = await this.treeBuilder.build();
      console.log(`Found ${tree.pages.size} pages, ${tree.attachments.length} attachments`);

      // Step 2: Create/update pages for each mapping
      for (const mapping of this.config.mappings) {
        console.log(`\nProcessing mapping: ${mapping.localRoot}`);

        // Get or create parent page
        let parentPageId = mapping.parentPageId;
        if (!parentPageId && mapping.parentPageTitle) {
          console.log(`Creating parent page: ${mapping.parentPageTitle}`);
          const parentPage = await this.client.createPage(
            this.config.confluence.spaceKey,
            null, // Root of space
            mapping.parentPageTitle,
            '<p>Auto-generated by Forma</p>'
          );
          parentPageId = parentPage.id;
        }

        if (!parentPageId) {
          result.errors.push(`No parent page ID or title for mapping: ${mapping.localRoot}`);
          continue;
        }

        // Get pages for this mapping
        const mappingPages = Array.from(tree.pages.entries())
          .filter(([key]) => key.startsWith(mapping.localRoot + '/'));

        // Build page ID map (repoPathKey -> confluencePageId)
        const pageMap = new Map<string, string>();

        // Step 3: Create pages in order (parents first)
        const sortedPages = this.sortByHierarchy(mappingPages, tree.pages);

        for (const [repoPathKey, page] of sortedPages) {
          try {
            const pageResult = await this.publishPage(
              page,
              parentPageId,
              tree.pages,
              tree.attachments.filter(a => a.ownerRepoPathKey === repoPathKey),
              pageMap
            );

            if (pageResult.created) {
              result.created.push(page.title);
            } else if (pageResult.updated) {
              result.updated.push(page.title);
            } else {
              result.unchanged.push(page.title);
            }

            pageMap.set(repoPathKey, pageResult.pageId);
          } catch (error) {
            const msg = error instanceof Error ? error.message : String(error);
            result.errors.push(`Failed to publish ${page.title}: ${msg}`);
          }
        }
      }
    } catch (error) {
      const msg = error instanceof Error ? error.message : String(error);
      result.errors.push(`Publish failed: ${msg}`);
    }

    return result;
  }

  private sortByHierarchy(
    pages: [string, PageNode][],
    allPages: Map<string, PageNode>
  ): [string, PageNode][] {
    // Sort so parents come before children
    const result: [string, PageNode][] = [];
    const added = new Set<string>();

    const addWithParents = (key: string, page: PageNode) => {
      if (added.has(key)) return;

      // Add parent first (if it's in this mapping)
      if (page.parentKey && allPages.has(page.parentKey)) {
        const parent = allPages.get(page.parentKey)!;
        if (!added.has(page.parentKey)) {
          addWithParents(page.parentKey, parent);
        }
      }

      result.push([key, page]);
      added.add(key);
    };

    for (const [key, page] of pages) {
      addWithParents(key, page);
    }

    return result;
  }

  private async publishPage(
    page: PageNode,
    mappingParentId: string,
    allPages: Map<string, PageNode>,
    attachments: AttachmentRef[],
    pageMap: Map<string, string>
  ): Promise<{ pageId: string; created: boolean; updated: boolean }> {
    // Read markdown content
    const markdown = await readFile(page.sourcePath, 'utf-8');

    // Convert to Confluence storage format
    const context = {
      pageMap,
      currentPageKey: page.repoPathKey,
      baseDir: dirname(page.sourcePath),
    };
    const storageContent = this.converter.convert(markdown, context);

    // Calculate content hash
    const contentHash = createHash('sha256').update(storageContent).digest('hex');

    // Determine Confluence parent
    let confluenceParentId = mappingParentId;
    if (page.parentKey && pageMap.has(page.parentKey)) {
      confluenceParentId = pageMap.get(page.parentKey)!;
    }

    // Check if page already exists (by content property first, then by title under parent)
    let existingPages = await this.client.findPagesByProperty(
      this.config.confluence.spaceKey,
      'forma-repo-path',
      page.repoPathKey
    );

    // Fallback: check by title under the parent page
    if (existingPages.length === 0) {
      const children = await this.client.getChildren(confluenceParentId);
      const byTitle = children.find(c => c.title === page.title);
      if (byTitle) {
        existingPages = [byTitle];
        console.log(`  Found existing page by title: ${page.title}`);
      }
    }

    let pageId: string;
    let created = false;
    let updated = false;

    if (existingPages.length > 0) {
      // Page exists - check if update needed
      pageId = existingPages[0].id;

      const existingProp = await this.client.getContentProperty(pageId, 'forma-content-hash');
      const existingHash = existingProp?.value as string | undefined;

      if (existingHash === contentHash && attachments.length === 0) {
        // No change and no attachments to upload
        console.log(`  Unchanged: ${page.title}`);
        return { pageId, created: false, updated: false };
      }

      // If content unchanged but has attachments, still proceed to upload them
      if (existingHash === contentHash) {
        console.log(`  Uploading attachments for: ${page.title}`);
      }

      // Update page
      console.log(`  Updating: ${page.title}`);
      const currentPage = await this.client.getPage(pageId, ['version']);
      await this.client.updatePage(pageId, page.title, storageContent, currentPage.version!);
      updated = true;

      // Update content hash
      const hashProp = await this.client.getContentProperty(pageId, 'forma-content-hash');
      await this.client.setContentProperty(pageId, 'forma-content-hash', contentHash, hashProp?.version);
    } else {
      // Create new page
      console.log(`  Creating: ${page.title}`);
      const newPage = await this.client.createPage(
        this.config.confluence.spaceKey,
        confluenceParentId,
        page.title,
        storageContent
      );
      pageId = newPage.id;
      created = true;

      // Set content properties
      await this.client.setContentProperty(pageId, 'forma-repo-path', page.repoPathKey);
      await this.client.setContentProperty(pageId, 'forma-content-hash', contentHash);
    }

    // Upload attachments
    for (const att of attachments) {
      try {
        const data = await readFile(att.sourcePath);
        console.log(`    Uploading: ${att.fileName}`);
        await this.client.uploadAttachment(pageId, att.fileName, data, att.mimeType || 'application/octet-stream');
      } catch (error) {
        console.warn(`    Warning: Could not upload ${att.fileName}: ${error}`);
      }
    }

    // Add labels if configured
    if (this.config.metadata.addLabelsFromFrontmatter && page.labels && page.labels.length > 0) {
      try {
        await this.client.addLabels(pageId, page.labels);
      } catch (error) {
        console.warn(`    Warning: Could not add labels: ${error}`);
      }
    }

    return { pageId, created, updated };
  }

  async plan(): Promise<PublishResult> {
    // Dry run - just show what would change without publishing
    const result: PublishResult = {
      created: [],
      updated: [],
      unchanged: [],
      warnings: [],
      errors: [],
    };

    const tree = await this.treeBuilder.build();

    for (const [repoPathKey, page] of tree.pages) {
      // Check if page exists
      const existingPages = await this.client.findPagesByProperty(
        this.config.confluence.spaceKey,
        'forma-repo-path',
        repoPathKey
      );

      if (existingPages.length > 0) {
        // Would check content hash here for update vs unchanged
        result.updated.push(page.title);
      } else {
        result.created.push(page.title);
      }
    }

    return result;
  }
}
